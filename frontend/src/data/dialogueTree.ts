export function getTree(scenarioId: string): DialogueNode[] {
  const t = TREES[scenarioId];
  if (t) return t;

  // ★ 自定义角色（X- 前缀）：用编辑器保存的台词树
  //   没有的话按阻抗形态现场生成一棵 —— 绝不能返回空数组，
  //   否则 generateReply 里 tree[tree.length-1] 会崩，白屏。
  // 教师自建案例没有预置台词树：直接走下面的通用兜底。
  // AI 开启时台词由模型按 system_prompt 生成；未开 AI 时用兜底树保证
  // 对话能推进（绝不返回空数组，否则渲染会崩）。

  // 最后兜底：任何未知 id 都给一棵通用树，绝不返回空
  console.warn('[叩门] 未找到台词树：' + scenarioId + '，已用通用兜底');
  return buildScriptTree('polite-avoidance');
}

/**
 * ★ 白名单校验：判断一句话是否来自台词库。
 *
 * 用法（渲染服务对象消息前必须调用）：
 *   if (!isScriptLine(text, scenarioId)) {
 *     text = getFallbackLine(scenarioId, nodeIndex);  // 回退到 A 变体
 *   }
 *
 * @param text 待校验的文本
 * @param scenarioId 剧本 id
 * @returns true = 该句确实来自台词库；false = 疑似幻觉产物，必须回退
 */
export function isScriptLine(text: string, scenarioId: string): boolean {
  if (!text) return true;
  const tree = getTree(scenarioId);
  // getTree 现在保证非空，这里不需要额外判断
  const pools: string[][] = [
    ...tree.map((n) => Object.values(n.lines)),
    [WANG_EXHAUSTED.A, WANG_EXHAUSTED.B, WANG_EXHAUSTED.C],
    DEFENSE_LINES.map((d) => d.text),
    Object.values(AZHEN_DETAIL_AVOID),
  ];
  // 打平成一个 Set，避免每次线性扫描。
  // ⚠️ 必须同时收录「原始行」与「strip 后非空的行」：
  //    纯标点台词（如 W-03A / W-16A / C-02A / M-02A 的「……」）strip 后是空串，
  //    只收 strip 结果就等于把它们从白名单里删掉了。
  const whitelist = new Set<string>();
  for (const pool of pools) {
    for (const line of pool) {
      if (!line) continue;
      whitelist.add(line);
      const plain = strip(line);
      if (plain) whitelist.add(plain);
    }
  }

  // ★ 台词可能是「节点台词 防御台词」的拼接（评判/建议过早时会追加），
  //   所以按全角空格切分，每一段都必须命中白名单才算合法。
  // strip 为空（纯标点）时回退比较原文。
  const parts = text.split('\u3000').filter((p) => p.trim().length > 0);
  if (parts.length === 0) return false;
  return parts.every((p) => {
    const key = strip(p) || p;
    return whitelist.has(p) || whitelist.has(key);
  });
}

/** 取回退台词：该节点的 A 变体（最保守） */
export function getFallbackLine(scenarioId: string, nodeIndex: number): string {
  const tree = getTree(scenarioId);
  const node = tree[Math.min(nodeIndex, tree.length - 1)];
  return node.lines.A;
}

function strip(s: string): string {
  return s.replace(/[\s，。！？、；：""''（）【】,.!?;:'"()[\]<>《》—…·]/g, '');
}