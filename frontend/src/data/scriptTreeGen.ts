/** 按阻抗形态生成一棵台词树 */
export function buildScriptTree(resistance: string): DialogueNode[] {
  const tpl = TEMPLATES[resistance] ?? GENERIC;
  return tpl.map((row, i) => ({
    id: `X-${String(i + 1).padStart(2, '0')}`,
    stage: STAGE_OF(i),
    topic: TOPIC_OF(row[0]),
    lines: { A: row[1], B: row[2], C: row[3] },
  }));
}

