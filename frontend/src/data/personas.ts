/** 拼出完整的 system prompt（persona + 难度 + 情绪档位） */
export function buildSystemPrompt(
  personaId: string,
  difficulty: Difficulty,
  emotion: number
): string {
  const p = PERSONAS.find(x => x.id === personaId);
  if (!p) return '';
  const band = emotion < 30 ? 'low' : emotion < 70 ? 'mid' : 'high';
  const parts = [
    p.systemPrompt,
    DIFFICULTY_RULES[difficulty],
    `【此刻你的情绪值：${emotion}（${band === 'low' ? '抵触' : band === 'mid' ? '观望' : '开放'}）】`,
    p.voiceByEmotion[band],
    `【你的绝对禁区】不要说出以下任何一句：${p.forbidden.join('、')}`,
    `【回复要求】
- 每次只回复 1 到 3 句，不要长篇大论
- 不要当老师，不要给社工任何建议或指导
- 不要使用社工专业术语（"共情""需求""评估"之类）
- 你只是一个正在经历困难的人，在和一个试图帮助你的人说话`,
  ];
  return parts.join('\n\n');
}